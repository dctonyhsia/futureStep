// 名詞搜尋
const items = [...document.querySelectorAll('#g-list > div')];
$('g-search').addEventListener('input', e => {
  const q = e.target.value.trim().toLowerCase();
  let shown = 0;
  items.forEach(it => {
    const hit = !q || it.textContent.toLowerCase().includes(q);
    it.hidden = !hit;
    if (hit) shown++;
  });
  $('g-empty').hidden = shown > 0;
});

